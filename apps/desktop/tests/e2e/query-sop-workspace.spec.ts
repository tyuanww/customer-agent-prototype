import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test, type ElectronApplication, type Page } from '@playwright/test';
import { launchSopElectron } from '../support/sop-electron';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const evidenceDir = process.env.CUSTOMER_AGENT_TEST_OUTPUT ?? path.join(root, '../../test-output/sop-workspace');
const bounds = (app: ElectronApplication) => app.evaluate(({ BrowserWindow }) => {
  const query = BrowserWindow.getAllWindows().find(win => win.webContents.getURL().includes('role=query'));
  if (!query) throw new Error('Query missing');
  return query.getBounds();
});
async function stable(query: Page, view?: 'sop' | 'query-home' | 'query-results') {
  if (view) await expect(query.getByTestId('query-shell')).toHaveAttribute('data-workspace-view', view);
  await expect(query.getByTestId('query-shell')).toHaveAttribute('data-view-transition', 'stable');
}
async function resize(query: Page, width: number, height: number) {
  await stable(query, 'sop');
  await query.evaluate(async ({ width, height }) => {
    const api = window.customerAgent?.sopWindow, snapshot = await api?.current?.();
    if (!api?.windowIntent || snapshot?.kind !== 'ready' || !snapshot.projection) throw new Error('SOP missing');
    const identity = { taskId: snapshot.projection.taskId, hostEpoch: snapshot.access.kind === 'executable' ? snapshot.access.hostEpoch : 0 }, gesture = Date.now();
    await api.windowIntent({ ...identity, type: 'resize-start', gesture, edge: 'se' });
    await api.windowIntent({ ...identity, type: 'resize', gesture, dx: width - innerWidth, dy: height - innerHeight });
    await api.windowIntent({ ...identity, type: 'resize-end', gesture });
  }, { width, height });
}

test('multi-task Query preserves each progress with one shared manual size while home hides Top3', async () => {
  fs.mkdirSync(evidenceDir, { recursive: true });
  const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'query-sop-workspace-'));
  const app = await launchSopElectron({ desktopRoot: root, userDataDirectory: userData });
  const originalClipboard = await app.evaluate(({ clipboard }) => clipboard.readText());
  try {
    await expect.poll(() => app.windows().length).toBeGreaterThanOrEqual(2);
    const fox = app.windows().find(page => page.url().includes('role=fox'));
    const query = app.windows().find(page => page.url().includes('role=query'));
    if (!fox || !query) throw new Error('Overlay windows missing');
    await fox.getByTestId('fox-button').click();
    await expect(query.getByTestId('query-shell')).toHaveAttribute('data-opening', 'false');
    await query.getByTestId('question-input').fill('少件了，没收到全部');
    await query.getByTestId('search-button').click();
    await query.getByRole('button', { name: '进入少件处理', exact: true }).click();
    await stable(query, 'sop');
    await resize(query, 500, 420);
    const firstSize = await bounds(app);
    await query.getByRole('checkbox', { name: '已核对订单应收数量' }).click();
    await expect(query.getByRole('checkbox', { name: '已核对订单应收数量' })).toBeChecked();
    await query.getByRole('checkbox', { name: '已核对实收数量和包裹信息' }).click();
    await expect(query.getByRole('checkbox', { name: '已核对实收数量和包裹信息' })).toBeChecked();
    await query.getByRole('radio', { name: '选择索取数量与包裹信息' }).click();
    await expect(query.getByRole('radio', { name: '选择索取数量与包裹信息' })).toBeChecked();
    await query.getByRole('region', { name: 'SOP 流程' }).focus();
    await query.keyboard.press('F6');
    await expect(query.getByText('步骤 2', { exact: true })).toBeVisible();
    await expect(query.getByTestId('sop-feedback')).toContainText('已复制步骤 1');
    await expect.poll(() => app.evaluate(({ clipboard }) => clipboard.readText())).toContain('订单应收到和实际收到的数量');
    await query.getByRole('button', { name: '返回搜索', exact: true }).click();
    await stable(query, 'query-home');
    const home = await bounds(app);
    expect(home.width).toBe(600);
    expect(home.height).toBeLessThan(firstSize.height);
    await expect(query.getByTestId('question-input')).toHaveValue('少件了，没收到全部');
    await expect(query.getByTestId('script-card-1')).toHaveCount(0);
    await query.screenshot({ path: path.join(evidenceDir, 'home-one-task.png') });
    const tasks = query.getByRole('region', { name: 'SOP 待办' });
    const taskArea = await tasks.boundingBox();
    if (!taskArea) throw new Error('Query task area missing');
    const beforeHomeDrag = await bounds(app);
    await query.mouse.move(taskArea.x + 24, taskArea.y + 4);
    await query.mouse.down();
    await query.mouse.move(taskArea.x + 48, taskArea.y + 24, { steps: 3 });
    await query.mouse.up();
    const afterHomeDrag = await bounds(app);
    expect(afterHomeDrag.x).toBeGreaterThan(beforeHomeDrag.x);
    expect(afterHomeDrag.y).toBeGreaterThan(beforeHomeDrag.y);
    expect(afterHomeDrag).toMatchObject({ width: beforeHomeDrag.width, height: beforeHomeDrag.height });
    await expect(query.getByTestId('question-input')).toHaveValue('少件了，没收到全部');
    await expect(query.getByTestId('query-shell')).toHaveAttribute('data-parked', 'false');
    await tasks.getByRole('button', { name: '结束 少件处理 #1', exact: true }).click();
    const confirmation = query.getByRole('dialog', { name: '结束流程？' });
    await expect(confirmation).toBeVisible();
    expect((await bounds(app)).height).toBe(home.height);
    const confirmBounds = await confirmation.boundingBox();
    if (!confirmBounds) throw new Error('Close confirmation missing');
    expect(confirmBounds.y + confirmBounds.height).toBeLessThanOrEqual(await query.evaluate(() => innerHeight));
    await query.screenshot({ path: path.join(evidenceDir, 'home-close-confirmation.png') });
    await confirmation.getByRole('button', { name: '取消', exact: true }).click();
    await expect.poll(async () => (await bounds(app)).height).toBe(home.height);

    await query.getByTestId('search-button').click();
    await query.getByRole('button', { name: '进入少件处理', exact: true }).click();
    await expect(query.getByText('步骤 1', { exact: true })).toBeVisible();
    await resize(query, 460, 500);
    const secondSize = await bounds(app);
    await query.getByRole('button', { name: '返回搜索', exact: true }).click();
    await stable(query, 'query-home');
    await expect(tasks.getByRole('button', { name: /少件处理.*#1.*步骤 2/ })).toHaveCount(1);
    await expect(tasks.getByRole('button', { name: /少件处理.*#2.*步骤 1/ })).toHaveCount(1);
    await tasks.getByRole('button', { name: /少件处理.*#1.*步骤 2/ }).click();
    await stable(query, 'sop');
    expect(await bounds(app)).toMatchObject({ width: secondSize.width, height: secondSize.height });
    await expect(query.getByText('步骤 2', { exact: true })).toBeVisible();
    await expect(query.getByRole('button', { name: '独立悬浮', exact: true })).toBeVisible();
    await query.getByRole('button', { name: '返回搜索', exact: true }).click();
    await stable(query, 'query-home');
    await tasks.getByRole('button', { name: /少件处理.*#2.*步骤 1/ }).click();
    await stable(query, 'sop');
    expect(await bounds(app)).toMatchObject({ width: secondSize.width, height: secondSize.height });
    await expect(query.getByText('步骤 1', { exact: true })).toBeVisible();
    const beforeDrag = await bounds(app);
    const blank = await query.getByTestId('sop-scroll-content').boundingBox();
    if (!blank) throw new Error('SOP body missing');
    await query.mouse.move(blank.x + 10, blank.y + 8);
    await query.mouse.down();
    await query.mouse.move(blank.x + 40, blank.y + 28, { steps: 3 });
    await query.mouse.up();
    const afterDrag = await bounds(app);
    expect(afterDrag.x).toBeGreaterThan(beforeDrag.x);
    expect(afterDrag.y).toBeGreaterThan(beforeDrag.y);
    expect(afterDrag).toMatchObject({ width: beforeDrag.width, height: beforeDrag.height });
    await query.getByRole('button', { name: '返回搜索', exact: true }).click();
    await stable(query, 'query-home');
    await query.getByTestId('question-input').fill('用了露芷面膜过敏了怎么办');
    await query.getByTestId('search-button').click();
    await expect(query.getByTestId('script-card-1')).toBeVisible();
    await query.getByTestId('sop-query-open-allergy-aftersale-demo').click();
    await stable(query, 'sop');
    await query.getByRole('button', { name: '返回搜索', exact: true }).click();
    await stable(query, 'query-home');
    await expect(query.getByTestId('question-input')).toBeFocused();
    await query.evaluate(() => { if (document.activeElement instanceof HTMLElement) document.activeElement.blur(); });
    const copiedBeforeHomeKeys = await app.evaluate(({ clipboard }) => clipboard.readText());
    for (const key of ['1', '2', '3']) await query.keyboard.press(key);
    expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toBe(copiedBeforeHomeKeys);
    await expect(query.getByTestId('question-input')).toHaveValue('用了露芷面膜过敏了怎么办');
    await query.keyboard.press('F7');
    await stable(query, 'query-home');
    await query.getByTestId('search-button').click();
    await expect(query.getByTestId('script-card-1')).toBeVisible();
    await tasks.getByRole('button', { name: '结束 少件处理 #1', exact: true }).click();
    const resultConfirm = query.getByRole('dialog', { name: '结束流程？' });
    await resultConfirm.focus();
    const beforeShortcuts = await app.evaluate(({ clipboard }) => clipboard.readText());
    await query.keyboard.press('F7');
    await query.keyboard.press('1');
    expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toBe(beforeShortcuts);
    await expect(resultConfirm).toBeVisible();
    await expect(query.getByTestId('query-shell')).toHaveAttribute('data-workspace-view', 'query-results');
    await resultConfirm.getByRole('button', { name: '结束流程', exact: true }).click();
    await expect(tasks.getByRole('button', { name: /少件处理.*#1.*步骤 2/ })).toHaveCount(0);
    await expect(tasks.getByRole('button', { name: /少件处理.*#2.*步骤 1/ })).toHaveCount(1);
    await expect(query.getByTestId('script-card-1')).toBeVisible();
    await query.screenshot({ path: path.join(evidenceDir, 'results-after-background-close.png') });
  } finally {
    await app.evaluate(({ clipboard }, value) => clipboard.writeText(value), originalClipboard);
    await app.close();
    fs.rmSync(userData, { recursive: true, force: true });
  }
});
